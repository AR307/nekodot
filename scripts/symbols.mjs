// Builds the icon font the client ships and the Dart names for its icons.
//
// The source names an icon as `Symbols.<name>`. This script collects those
// names, looks them up in Material Symbols Outlined (the material_symbols_icons
// dev dependency), writes apps/native/lib/ui/symbols.dart, and cuts the font
// down to those glyphs with Flutter's own font-subset tool, which keeps the
// weight axis. Run it after naming an icon the font does not hold yet:
//
//   node scripts/symbols.mjs
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const native = resolve(root, 'apps/native');
const sdk = process.env.FLUTTER_ROOT ?? resolve(root, '.runtime/side-phase-3/flutter');
const names = join(native, 'lib/ui/symbols.dart');
const font = join(native, 'assets/fonts/material-symbols.ttf');

const packages = JSON.parse(
  readFileSync(join(native, '.dart_tool/package_config.json'), 'utf8'),
).packages;
const source = fileURLToPath(
  packages.find((p) => p.name === 'material_symbols_icons').rootUri + '/',
);

// Every Dart file that can name an icon, except the generated one.
const files = [];
const walk = (folder) => {
  for (const entry of readdirSync(folder, { withFileTypes: true })) {
    const path = join(folder, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (entry.name.endsWith('.dart') && path !== names) files.push(path);
  }
};
for (const folder of ['lib', 'test', 'integration_test']) walk(join(native, folder));
const used = new Set();
for (const file of files) {
  for (const match of readFileSync(file, 'utf8').matchAll(/\bSymbols\.([a-z0-9_]+)/g))
    used.add(match[1]);
}

const codes = new Map(
  [
    ...readFileSync(join(source, 'lib/symbols.dart'), 'utf8').matchAll(
      /static const IconData (\w+) =\s*IconData\(0x([0-9a-f]+), fontFamily: 'MaterialSymbolsOutlined'/g,
    ),
  ].map((match) => [match[1], match[2]]),
);
const unknown = [...used].filter((name) => !codes.has(name));
if (unknown.length) throw new Error('Not in Material Symbols: ' + unknown.join(', '));

const sorted = [...used].sort();
writeFileSync(
  names,
  [
    '// Generated by scripts/symbols.mjs. Name an icon in the code, then run it.',
    '// ignore_for_file: constant_identifier_names',
    "import 'package:flutter/widgets.dart';",
    '',
    '/// The icons the client uses, from Material Symbols Outlined. Their weight',
    '/// and optical size come from the icon theme.',
    'abstract final class Symbols {',
    "  static const _family = 'Material Symbols';",
    ...sorted.map(
      (name) => `  static const ${name} = IconData(0x${codes.get(name)}, fontFamily: _family);`,
    ),
    '}',
    '',
  ].join('\n'),
);

const engine = join(sdk, 'bin/cache/artifacts/engine');
const subset = readdirSync(engine)
  .flatMap((host) => ['font-subset.exe', 'font-subset'].map((name) => join(engine, host, name)))
  .find(existsSync);
if (!subset) throw new Error('font-subset is missing from the Flutter SDK. Run "flutter doctor".');
execFileSync(subset, [font, join(source, 'lib/fonts/MaterialSymbolsOutlined.ttf')], {
  input: sorted.map((name) => parseInt(codes.get(name), 16)).join(' '),
  stdio: ['pipe', 'ignore', 'inherit'],
});
console.log(`${sorted.length} icons → ${names} and ${font}`);
